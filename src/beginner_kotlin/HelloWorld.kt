package beginner_kotlin

fun main() {
    println("Hello World!")
}
// fun: Keyword to declare a function (Function declaration start point)
// main(): The Entry Point of the program. Execution starts here.
// { ... }: The 'Scope' or 'Body' of the function. Everything inside is executed.
// println(): Prints the text and moves the cursor to a NEW line.
// print(): Prints the text but stays on the SAME line.